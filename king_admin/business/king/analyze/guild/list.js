exports.exec = async function (body, query, ctx) {
    const {
        bundle,
        servid,
        date,
        _sort_
    } = body;


    const $match = {};
    if (date && date[1]) {
        const [start, end] = this.parseDateMatch(date);
        // 两边数据表时间格式不一样， 分开 写条件
        $match.create = {
            $gte: start,
            $lte: end
        };
    } else {
        const n = new Date();
        n.setDate(n.getDate() - 7);
        n.setHours(0, 0, 0, 0);
        $match.create = {
            $gte: n.getTime(),
        }
    }

    if (servid && servid !== 'ALL') {
        $match.servid = +servid;
    } else {
        const servers = await this.service.game.serversOptions(ctx.adminRole);
        if (!servers.__is_all__)  // 被隔离了
            $match['servid'] = {
                $in: servers.map(s => s.value)
            }
    }

    if (bundle && bundle.length) {
        $match.bundle = {
            $in: bundle
        };
    }
    const sort = {};
    if (_sort_ && _sort_.field) {
        sort[_sort_.field] = _sort_.order;
    } else {
        sort._id = -1;
    }

    const roleModel = await this.service.game.collection('roles');
    const agg = [
        {
            $match: $match
        },
        {

            $project: {
                _id: 1,
                last_step: 1
            }
        },
        {
            $group: {
                _id: "$last_step",
                count: {$sum: 1}
            }
        },
        {
            $sort: sort
        }

    ];
    console.log(JSON.stringify(agg));
    const c = await roleModel.aggregate(agg, {allowDiskUse: true});
    const items = await c.toArray();
    items.forEach(item => {
        item._id = item._id || '跳过引导';
        item.desc = step_config[item._id] || '跳过引导';
    })
    return {
        items,
        total: items.length
    }
}
